/**
 * Writes the TMDB key into a generated `TmdbKey.kt` so the app never needs a committed key.
 * The value is a configuration-cache input, so a changed key file or env value regenerates.
 */
abstract class GenerateTmdbKey : DefaultTask() {
    @get:Input
    abstract val apiKey: Property<String>

    @get:OutputDirectory
    abstract val outputDir: DirectoryProperty

    @TaskAction
    fun generate() {
        val key = apiKey.get().trim().let { raw ->
            val quoted = raw.length >= 2 &&
                ((raw.startsWith('"') && raw.endsWith('"')) || (raw.startsWith('\'') && raw.endsWith('\'')))
            if (quoted) raw.substring(1, raw.length - 1) else raw
        }.trim()
        if (key.isNotEmpty() && !Regex("^[A-Za-z0-9._-]+$").matches(key)) {
            throw GradleException("tmdb.properties: TMDB_API_KEY contains characters a TMDB key cannot have")
        }
        val literal = key
            .replace("\\", "\\\\")
            .replace("\"", "\\\"")
            .replace("$", "\\$")
        val dir = outputDir.get().asFile.resolve("io/github/sh3lan93/mobileautomator/showcase")
        dir.mkdirs()
        dir.resolve("TmdbKey.kt").writeText(
            """
            |// Generated by :shared:generateTmdbKey from tmdb.properties or the TMDB_API_KEY env var. Do not edit.
            |package io.github.sh3lan93.mobileautomator.showcase
            |
            |internal const val TMDB_API_KEY: String = "$literal"
            |""".trimMargin()
        )
    }
}

val tmdbKeyFromFile = providers
    .fileContents(rootProject.layout.projectDirectory.file("tmdb.properties"))
    .asText
    .map { text -> Properties().apply { load(StringReader(text)) }.getProperty("TMDB_API_KEY") }

val generateTmdbKey = tasks.register<GenerateTmdbKey>("generateTmdbKey") {
    apiKey.set(tmdbKeyFromFile.orElse(providers.environmentVariable("TMDB_API_KEY")).orElse(""))
    outputDir.set(layout.buildDirectory.dir("generated/tmdbKey/commonMain/kotlin"))
}

